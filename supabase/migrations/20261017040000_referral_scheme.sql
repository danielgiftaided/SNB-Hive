-- Private referral attribution, verified-payment rewards and atomic redemption.
begin;
create schema if not exists snb_private;
alter table public.users add column if not exists referral_signup_code text;
create table if not exists snb_private.referral_codes (
  user_id text primary key references public.users(id) on delete cascade deferrable initially deferred,
  access_email text not null,
  code text not null unique default ('HIVE-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,10)))
);
insert into snb_private.referral_codes(user_id,access_email) select id,coalesce(lower(btrim(email)),'') from public.users on conflict do nothing;
create table if not exists snb_private.referrals (
  id uuid primary key default gen_random_uuid(),
  referred_id text not null unique references public.users(id) on delete cascade deferrable initially deferred,
  referrer_id text not null references public.users(id) on delete cascade,
  created_at timestamptz not null default clock_timestamp(),
  earned_at timestamptz, payment_id text unique,
  booking_id text, redemption_count integer not null default 0,
  check (referred_id <> referrer_id)
);
create index if not exists referrals_by_referrer on snb_private.referrals(referrer_id);
create table if not exists snb_private.referral_checkouts (
  billing_request_id text primary key, booking_id text not null unique,
  user_id text not null references public.users(id), created_at timestamptz not null default clock_timestamp()
);
create table if not exists snb_private.referral_redemptions (
  booking_id text primary key, referral_id uuid not null references snb_private.referrals(id),
  user_id text not null references public.users(id)
);
revoke all on schema snb_private from public,anon,authenticated;
revoke all on snb_private.referral_codes,snb_private.referrals,snb_private.referral_checkouts,snb_private.referral_redemptions from public,anon,authenticated;

-- Isolated server-verified access for the new value-bearing feature. Codes
-- are generated by the function, never supplied by a browser to the mailer.
create table if not exists snb_private.referral_access_challenges (
  user_id text primary key references public.users(id) on delete cascade,
  code_hash text not null, expires_at timestamptz not null, attempts integer not null default 0,
  sent_at timestamptz not null, send_day date not null, send_count integer not null
);
create table if not exists snb_private.referral_access_sessions (
  token_hash text primary key, user_id text not null references public.users(id) on delete cascade,
  expires_at timestamptz not null
);
revoke all on snb_private.referral_access_challenges,snb_private.referral_access_sessions from public,anon,authenticated;
create or replace function public.prepare_referral_access(p_member_id text,p_code_hash text)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare challenge snb_private.referral_access_challenges%rowtype; member public.users%rowtype; trusted_email text;
begin
  if coalesce(p_code_hash,'') !~ '^[a-f0-9]{64}$' then raise exception 'Invalid verification request'; end if;
  select * into member from public.users where id=p_member_id for update;
  if not found then raise exception 'Member account not found'; end if;
  select * into challenge from snb_private.referral_access_challenges where user_id=p_member_id;
  if challenge.sent_at > clock_timestamp()-interval '60 seconds' then raise exception 'Please wait one minute before requesting another code'; end if;
  if challenge.send_day=current_date and challenge.send_count>=10 then raise exception 'Too many codes requested. Please try again tomorrow'; end if;
  insert into snb_private.referral_access_challenges(user_id,code_hash,expires_at,attempts,sent_at,send_day,send_count)
    values(p_member_id,p_code_hash,clock_timestamp()+interval '15 minutes',0,clock_timestamp(),current_date,1)
    on conflict(user_id) do update set code_hash=excluded.code_hash,expires_at=excluded.expires_at,attempts=0,
      sent_at=excluded.sent_at,send_day=excluded.send_day,
      send_count=case when referral_access_challenges.send_day=current_date then referral_access_challenges.send_count+1 else 1 end;
  select access_email into trusted_email from snb_private.referral_codes where user_id=p_member_id;
  return jsonb_build_object('email',trusted_email,'name',member.name);
end $$;
create or replace function public.verify_referral_access(p_member_id text,p_code_hash text,p_token_hash text)
returns boolean language plpgsql security definer set search_path=public,pg_temp as $$
declare challenge snb_private.referral_access_challenges%rowtype;
begin
  select * into challenge from snb_private.referral_access_challenges where user_id=p_member_id for update;
  if not found or challenge.expires_at<clock_timestamp() or challenge.attempts>=5 or coalesce(p_token_hash,'') !~ '^[a-f0-9]{64}$' then return false; end if;
  update snb_private.referral_access_challenges set attempts=attempts+1 where user_id=p_member_id;
  if p_code_hash is distinct from challenge.code_hash then return false; end if;
  update snb_private.referral_access_challenges set attempts=5,expires_at=clock_timestamp()-interval '1 second' where user_id=p_member_id;
  delete from snb_private.referral_access_sessions where expires_at<clock_timestamp();
  insert into snb_private.referral_access_sessions values(p_token_hash,p_member_id,clock_timestamp()+interval '30 days');
  return true;
end $$;
create or replace function public.authorize_referral_access(p_member_id text,p_token_hash text)
returns boolean language sql security definer set search_path=public,pg_temp as $$
  select exists(select 1 from snb_private.referral_access_sessions where user_id=p_member_id and token_hash=p_token_hash and expires_at>clock_timestamp());
$$;
create or replace function public.revoke_referral_access(p_member_id text,p_token_hash text)
returns boolean language plpgsql security definer set search_path=public,pg_temp as $$
begin
  delete from snb_private.referral_access_sessions where user_id=p_member_id and token_hash=p_token_hash;
  return found;
end $$;
revoke all on function public.prepare_referral_access(text,text),public.verify_referral_access(text,text,text),public.authorize_referral_access(text,text),public.revoke_referral_access(text,text) from public,anon,authenticated;
grant execute on function public.prepare_referral_access(text,text),public.verify_referral_access(text,text,text),public.authorize_referral_access(text,text),public.revoke_referral_access(text,text) to service_role;

-- Consume a code only on first INSERT. Never persist a public referral graph,
-- and never let profile/password upserts create or replace attribution.
create or replace function public.capture_signup_referral()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
declare owner_id text; owner_email text;
begin
  if TG_OP='UPDATE' or exists(select 1 from public.users where id=NEW.id) then
    NEW.referral_signup_code := null; return NEW;
  end if;
  insert into snb_private.referral_codes(user_id,access_email) values(NEW.id,coalesce(lower(btrim(NEW.email)),'')) on conflict do nothing;
  if nullif(btrim(NEW.referral_signup_code),'') is not null then
    select c.user_id,c.access_email into owner_id,owner_email from snb_private.referral_codes c
      join public.users u on u.id=c.user_id where c.code=upper(btrim(NEW.referral_signup_code));
    if owner_id is null then raise exception 'This referral code was not found. Check the code or remove it to register without a referral.'; end if;
    if owner_id=NEW.id or lower(btrim(owner_email))=lower(btrim(NEW.email)) then raise exception 'You cannot refer yourself'; end if;
    if exists(select 1 from public.users where lower(btrim(email))=lower(btrim(NEW.email))) then
      raise exception 'Referral codes are for new accounts only'; end if;
    insert into snb_private.referrals(referred_id,referrer_id) values(NEW.id,owner_id);
  end if;
  NEW.referral_signup_code := null;
  return NEW;
end $$;
drop trigger if exists users_capture_referral on public.users;
create trigger users_capture_referral before insert or update on public.users for each row execute function public.capture_signup_referral();

create or replace function public.bind_referral_checkout(p_billing_request_id text,p_booking_id text,p_member_id text)
returns boolean language plpgsql security definer set search_path=public,pg_temp as $$
begin
  if not exists(select 1 from snb_private.referrals where referred_id=p_member_id) then return false; end if;
  insert into snb_private.referral_checkouts(billing_request_id,booking_id,user_id)
    values(p_billing_request_id,p_booking_id,p_member_id) on conflict do nothing;
  if not exists(select 1 from snb_private.referral_checkouts where billing_request_id=p_billing_request_id and booking_id=p_booking_id and user_id=p_member_id) then
    raise exception 'Referral checkout does not match the original member'; end if;
  return true;
end $$;
create or replace function public.referral_checkout_for_booking(p_booking_id text)
returns jsonb language sql security definer set search_path=public,pg_temp as $$
  select jsonb_build_object('billing_request_id',billing_request_id,'user_id',user_id) from snb_private.referral_checkouts where booking_id=p_booking_id;
$$;
-- Only trusted provider reconciliation can fund a reward. One row per new
-- member makes renewals, duplicate events and concurrent delivery idempotent.
create or replace function public.award_referral_reward(p_details jsonb)
returns boolean language plpgsql security definer set search_path=public,pg_temp as $$
begin
  if p_details->>'status' not in ('confirmed','paid_out') or coalesce(p_details->>'payment_id','') !~ '^PM[a-zA-Z0-9_-]+$'
    or p_details->>'currency' is distinct from 'GBP' or coalesce((p_details->>'amount')::integer,0)<=0 then return false; end if;
  update snb_private.referrals r set earned_at=clock_timestamp(),payment_id=p_details->>'payment_id'
    from snb_private.referral_checkouts c where c.billing_request_id=p_details->>'billing_request_id'
      and c.user_id=r.referred_id and r.earned_at is null
      and (p_details->>'created_at')::timestamptz >= r.created_at;
  return found;
end $$;
create or replace function public.referral_dashboard(p_member_id text)
returns jsonb language sql security definer set search_path=public,pg_temp as $$
  select jsonb_build_object('code',c.code,
    'pending',(select count(*) from snb_private.referrals where referrer_id=c.user_id and earned_at is null),
    'earned',(select count(*) from snb_private.referrals where referrer_id=c.user_id and earned_at is not null),
    'credits',coalesce((select jsonb_agg(jsonb_build_object('id',r.id,'earned_at',r.earned_at) order by r.earned_at)
      from snb_private.referrals r where r.referrer_id=c.user_id and earned_at is not null and booking_id is null),'[]'::jsonb))
  from snb_private.referral_codes c where c.user_id=p_member_id;
$$;

create or replace function public.redeem_referral_reward(p_member_id text,p_credit_id uuid,p_session_id text,p_booking_date date)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare reward snb_private.referrals%rowtype; member public.users%rowtype; booking public.bookings%rowtype; new_id text;
begin
  select * into reward from snb_private.referrals where id=p_credit_id and referrer_id=p_member_id for update;
  if not found or reward.earned_at is null then raise exception 'This free lesson is not available'; end if;
  if reward.booking_id is not null then
    select * into booking from public.bookings where id=reward.booking_id;
    if booking.status in ('paid','confirmed') and booking.session_id=p_session_id and booking.booking_date=p_booking_date then
      return jsonb_build_object('booking_id',booking.id,'already_redeemed',true); end if;
    raise exception 'This free lesson has already been used';
  end if;
  if p_session_id is null or p_session_id not in ('zumba','boxfit') or p_booking_date is null
    or extract(isodow from p_booking_date) <> (case when p_session_id='zumba' then 5 else 4 end)
    or (p_booking_date + case when p_session_id='zumba' then time '13:00' else time '14:00' end) <= (clock_timestamp() at time zone 'Europe/London') then
    raise exception 'Please choose an available Zumba or BoxFit date'; end if;
  perform pg_advisory_xact_lock(hashtext(p_session_id||p_booking_date::text));
  if exists(select 1 from public.bookings where user_id=p_member_id and session_id=p_session_id and booking_date=p_booking_date and status in ('paid','confirmed')) then
    raise exception 'You already have a booking for this class date'; end if;
  if (select count(*) from public.bookings where session_id=p_session_id and booking_date=p_booking_date
    and (status in ('paid','confirmed') or (status='pending_payment' and gocardless_payment_id like 'PM%')))
    >= (case when p_session_id='zumba' then 12 else 18 end) then raise exception 'This class is full. Please choose another date'; end if;
  select * into member from public.users where id=p_member_id;
  select access_email into member.email from snb_private.referral_codes where user_id=p_member_id;
  new_id := 'referral-'||reward.id::text||'-'||(reward.redemption_count+1)::text;
  update snb_private.referrals set booking_id=new_id,redemption_count=redemption_count+1 where id=reward.id;
  insert into snb_private.referral_redemptions values(new_id,reward.id,p_member_id);
  insert into public.bookings(id,user_id,name,email,phone,session_id,session_name,type,plan,amount,status,booking_date,payment_group_id)
    values(new_id,member.id,member.name,member.email,member.phone,p_session_id,case when p_session_id='zumba' then 'Zumba' else 'BoxFit' end,
      'class','Referral reward',0,'confirmed',p_booking_date,new_id);
  return jsonb_build_object('booking_id',new_id,'already_redeemed',false);
end $$;

-- Protect reward bookings from public writes and restore a credit only when
-- cancellation is at least 24 hours before the London class start time.
create or replace function public.protect_referral_booking()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
declare redemption snb_private.referral_redemptions%rowtype;
begin
  select * into redemption from snb_private.referral_redemptions where booking_id=NEW.id;
  if TG_OP='INSERT' then
    if NEW.plan='Referral reward' and (redemption.booking_id is null or NEW.user_id is distinct from redemption.user_id) then raise exception 'A verified referral credit is required'; end if;
  elsif redemption.booking_id is not null then
    if (to_jsonb(NEW)-'status'-'booking_confirmation_sent_at'-'payment_confirmation_sent_at') is distinct from
       (to_jsonb(OLD)-'status'-'booking_confirmation_sent_at'-'payment_confirmation_sent_at')
       or (NEW.status is distinct from OLD.status and NEW.status is distinct from 'cancelled') then raise exception 'Referral bookings can only be cancelled'; end if;
    if NEW.status='cancelled' and OLD.status<>'cancelled' and
      ((OLD.booking_date + case when OLD.session_id='zumba' then time '12:00' else time '13:00' end) at time zone 'Europe/London') >= clock_timestamp()+interval '24 hours' then
      update snb_private.referrals set booking_id=null where id=redemption.referral_id and booking_id=OLD.id;
    end if;
  elsif NEW.plan='Referral reward' then raise exception 'A verified referral credit is required';
  end if;
  return NEW;
end $$;
drop trigger if exists bookings_protect_referral on public.bookings;
create trigger bookings_protect_referral before insert or update on public.bookings for each row execute function public.protect_referral_booking();

revoke all on function public.capture_signup_referral() from public,anon,authenticated;
revoke all on function public.protect_referral_booking() from public,anon,authenticated;
revoke all on function public.bind_referral_checkout(text,text,text) from public,anon,authenticated;
revoke all on function public.referral_checkout_for_booking(text) from public,anon,authenticated;
revoke all on function public.award_referral_reward(jsonb) from public,anon,authenticated;
revoke all on function public.referral_dashboard(text) from public,anon,authenticated;
revoke all on function public.redeem_referral_reward(text,uuid,text,date) from public,anon,authenticated;
grant execute on function public.bind_referral_checkout(text,text,text),public.referral_checkout_for_booking(text),public.award_referral_reward(jsonb),public.referral_dashboard(text),public.redeem_referral_reward(text,uuid,text,date) to service_role;
notify pgrst,'reload schema';
commit;
